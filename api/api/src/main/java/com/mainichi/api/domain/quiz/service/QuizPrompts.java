package com.mainichi.api.domain.quiz.service;

import com.mainichi.api.domain.card.entity.JlptLevel;
import com.mainichi.api.domain.quiz.entity.QuizSourceCard;

import java.util.List;
import java.util.stream.Collectors;

/** 독해·청해 문제를 만드는 프롬프트. 어떤 AI 를 쓰든 같은 지시를 보낸다. */
final class QuizPrompts {

    private QuizPrompts() {}

    /** 독해·청해 공통: 문제 형식과 후리가나 규칙 */
    private static final String COMMON_RULES = """
            【問題】
            - 2問とも本文（会話）を理解しないと答えられない内容理解の問題にする。
            - 選択肢はちょうど4つ。正解は1つだけで、誤答も本文の語句を使ったもっともらしいものにする。
            - 正解の位置は2問で偏らないようにする。
            - explanation（解説）は韓国語で、正解の理由と本文中の根拠を2〜3文で書く。

            【ふりがな】
            韓国語の項目（translation・explanation）以外のすべての漢字に、漢字のすぐ後ろの角かっこで読みを付ける。
            送り仮名はかっこの外に出す。例：今日[きょう]は忙[いそが]しい。食[た]べました。
            かな・カタカナ・記号には付けない。
            """;

    /** 독해 시스템 프롬프트 */
    static final String READING = """
            あなたは韓国人の日本語学習者向けに、JLPT「読解（内容理解）」形式の練習問題を作る作問者です。

            学習者が今日はじめて覚えた単語・文法の一覧を受け取ります。それらを使った読解文を一つ書き、
            JLPT本試験と同じ形式の四択問題を2問作ってください。

            【本文】
            - 指定されたレベルの語彙・文法・漢字で書く。一覧にない語は、そのレベル以下のものだけを使う。
            - 一覧の単語・文法は、文脈に自然に合うものをできるだけ多く使う。不自然に詰め込まない。
              活用させてよい（例：食べる→食べました）。
            - 長さの目安（全角文字数）：基礎＝120字前後、N5＝200字、N4＝250字、N3＝350字、N2＝450字、N1＝550字。
            - 「基礎」レベルは漢字を使わず、ひらがな・カタカナだけで、ごく短い文で書く。
            - ジャンルはJLPTに出るもの（日記、手紙・メール、お知らせ、エッセイ、説明文など）から、内容に合うものを選ぶ。
            - 段落は空行で区切る。
            - 1問目は本文の具体的な内容や理由（「なぜ〜か」「〜について正しいものはどれか」など）、
              2問目は筆者の言いたいこと・本文全体の内容を問う。
            - translation は本文全体の自然な韓国語訳。

            """ + COMMON_RULES;

    /** 청해 시스템 프롬프트 */
    static final String LISTENING = """
            あなたは韓国人の日本語学習者向けに、JLPT「聴解」形式の練習問題を作る作問者です。
            作った会話は、ブラウザの音声合成で男性・女性の声に分けて読み上げます。

            指定されたレベルに合った、男の人と女の人の会話を一つ作り、JLPT本試験と同じ形式の四択問題を2問作ってください。

            【会話】
            - 指定されたレベルの語彙・文法で書く。今日覚えた単語・文法の一覧があれば、自然に合うものを会話に入れる。
              一覧がなければ、そのレベルでよく出る日常の場面（店、駅、学校、会社、家、病院など）から選ぶ。
            - 長さの目安（セリフの数）：基礎＝4〜6、N5＝6〜8、N4＝8〜10、N3＝10〜12、N2＝12〜14、N1＝14〜16。
            - 「基礎」レベルは漢字を使わず、ひらがな・カタカナだけで、ごく短いセリフにする。
            - N3以上は相づち（ええ、そうですね）、言い直し、縮約形（〜ちゃう、〜てる）など自然な話し言葉を入れ、
              N2・N1では途中で考えが変わる、条件が後から付くなど、聞き取りに注意が必要な展開を入れる。
            - 男女は交互に話すのが基本。situation は会話の前に読み上げる一文で、場面と登場人物だけを言う。
            - 音声で聞くので、括弧書き・記号・ト書きは使わない。

            【問題の種類】
            - 1問目は課題理解（「男の人はこのあと何をしますか」など、これからすること・選ぶもの）か
              ポイント理解（「女の人はどうして〜ましたか」など理由・具体的な点）。
            - 2問目は1問目と違う点を問う（会話全体の内容、話者の気持ち・意見など）。
            - 質問文は音声でも読むので、短くはっきり書く。
            - translation は situation と会話の韓国語訳。一行に一つのセリフで「남: …」「여: …」と書く。

            """ + COMMON_RULES;

    /** 학습 단계와 오늘 배운 카드 (사용자 메시지) */
    static String user(int level, List<QuizSourceCard> cards) {
        String levelName = level == JlptLevel.BASIC ? "基礎（ひらがな・カタカナ）" : "N" + level;
        if (cards.isEmpty()) {
            return "レベル：%s\n\n今日覚えた単語・文法：なし".formatted(levelName);
        }
        String list = cards.stream()
                .map(c -> c.grammar()
                        ? "- [文法] %s（%s）: %s".formatted(c.front(), c.usage(), c.meaning())
                        : "- [単語] %s : %s".formatted(c.front(), c.meaning()))
                .collect(Collectors.joining("\n"));
        return """
                レベル：%s

                今日はじめて覚えた単語・文法（読みは角かっこ、意味は韓国語）：
                %s
                """.formatted(levelName, list);
    }
}
